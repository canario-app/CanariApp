<?php

declare(strict_types=1);

namespace CanariApp\Backend\Controllers;

use CanariApp\Backend\Helpers\AuditHelper;
use CanariApp\Backend\Helpers\ResponseHelper;
use CanariApp\Backend\Helpers\Sanitizer;
use CanariApp\Backend\Middlewares\AuthMiddleware;
use CanariApp\Backend\Models\Backup;
use RuntimeException;
use Throwable;

/**
 * Controlador administrativo para generar, rotar y restaurar respaldos (SRS-RF029, DAT-003).
 *
 * Mantiene como máximo los 7 respaldos más recientes en la tabla respaldo
 * y ejecuta respaldo automático cuando han transcurrido 48 horas (2 días)
 * desde el último respaldo registrado.
 */
class BackupController {
    private const SERVER_FIELDS = [
        'id_respaldo',
        'fecha_hora',
        'id_usuario',
    ];

    private Backup $backupModel;

    public function __construct(?Backup $backupModel = null) {
        $this->backupModel = $backupModel ?? new Backup();
    }

    /**
     * [Admin] Lista los respaldos vigentes (máximo 7 más recientes).
     * Verifica además la política de respaldo automático cada 2 días (48h).
     */
    public function index(): void {
        $this->ensureAdminRole();

        try {
            $autoGenerated = $this->runAutomaticBackupIfDue();
            $items = $this->backupModel->findAllDetailed();

            ResponseHelper::success([
                'items'                  => $items,
                'total'                  => count($items),
                'max_retention'          => Backup::MAX_RETENTION,
                'auto_backup_interval_h' => (int) (Backup::AUTO_BACKUP_INTERVAL_SECONDS / 3600),
                'auto_backup_triggered'  => $autoGenerated !== null,
            ], 'Listado de respaldos obtenido.');
        } catch (Throwable) {
            ResponseHelper::internalError('No se pudieron obtener los respaldos.');
        }
    }

    /**
     * [Admin] Muestra el detalle de un respaldo registrado.
     */
    public function show(int|string $id): void {
        $this->ensureAdminRole();

        $idRespaldo = Sanitizer::int($id, 1);
        if ($idRespaldo === null) {
            ResponseHelper::badRequest('El ID del respaldo no es válido.');
            return;
        }

        try {
            $item = $this->backupModel->findDetailed($idRespaldo);
            if ($item === null) {
                ResponseHelper::notFound('Respaldo no encontrado.');
                return;
            }

            ResponseHelper::success($item, 'Detalle del respaldo obtenido.');
        } catch (Throwable) {
            ResponseHelper::internalError('No se pudo obtener el respaldo.');
        }
    }

    /**
     * [Admin] Genera/registra un respaldo y rota los excedentes más allá de los 7 más recientes.
     * Si pg_dump falla, aborta sin registrar en base de datos ni eliminar respaldos previos.
     */
    public function store(): void {
        $adminUserId = $this->ensureAdminRole();

        $input = $this->readOptionalJsonBody();
        $errors = $this->validateCreate($input);
        if ($errors !== []) {
            ResponseHelper::validationError($errors);
            return;
        }

        $requestedFile = is_string($input['archivo'] ?? null) ? trim($input['archivo']) : '';
        $fileName = $requestedFile !== ''
            ? $requestedFile
            : sprintf('canariapp_backup_%s_%s.sql', date('Ymd_His'), bin2hex(random_bytes(3)));

        $motivo = is_string($input['motivo'] ?? null) && trim($input['motivo']) !== ''
            ? trim($input['motivo'])
            : 'Generación y registro de respaldo administrativo';

        if (!$this->createPhysicalDump($fileName)) {
            ResponseHelper::internalError(
                'No se pudo generar el archivo de respaldo con pg_dump; no se registró el respaldo ni se aplicó la rotación.'
            );
            return;
        }

        try {
            $result = $this->backupModel->registerAndRotate($fileName, $adminUserId);
            if (is_string($result)) {
                $this->removePhysicalBackupIfExists($fileName);
                $this->respondDomainError($result);
                return;
            }

            $createdId = $result['id_respaldo'];
            $rotatedFiles = $result['rotated_files'];

            foreach ($rotatedFiles as $expiredFile) {
                $this->removePhysicalBackupIfExists($expiredFile);
            }

            $created = $this->backupModel->findDetailed($createdId) ?? [
                'id_respaldo' => $createdId,
                'archivo'     => $fileName,
                'id_usuario'  => $adminUserId,
            ];

            AuditHelper::log(
                action: 'insert',
                entity: 'respaldo',
                recordId: $createdId,
                newValue: [
                    'archivo' => $fileName,
                    'rotados' => $rotatedFiles,
                ],
                reason: $motivo,
                userId: $adminUserId
            );

            ResponseHelper::created([
                'respaldo' => $created,
                'rotados'  => $rotatedFiles,
            ], 'Respaldo registrado y rotación aplicada exitosamente.');
        } catch (Throwable) {
            $this->removePhysicalBackupIfExists($fileName);
            ResponseHelper::internalError('No se pudo registrar el respaldo.');
        }
    }

    /**
     * [Admin] Restaura la base de datos a partir de un respaldo registrado (SRS-RF029).
     * POST /api/v1/admin/respaldos/{id}/restaurar
     */
    public function restore(int|string $id): void {
        $adminUserId = $this->ensureAdminRole();

        $idRespaldo = Sanitizer::int($id, 1);
        if ($idRespaldo === null) {
            ResponseHelper::badRequest('El ID del respaldo no es válido.');
            return;
        }

        $input = $this->readOptionalJsonBody();
        if (array_key_exists('motivo', $input) && $input['motivo'] !== null && !is_string($input['motivo'])) {
            ResponseHelper::validationError(['motivo' => 'El motivo debe ser una cadena de texto.']);
            return;
        }

        $motivo = is_string($input['motivo'] ?? null) && trim($input['motivo']) !== ''
            ? trim($input['motivo'])
            : sprintf('Restauración de base de datos desde respaldo #%d (RF029)', $idRespaldo);

        try {
            $backup = $this->backupModel->findDetailed($idRespaldo);
            if ($backup === null) {
                ResponseHelper::notFound('Respaldo no encontrado.');
                return;
            }

            $safeName = basename(trim((string) $backup['archivo']));
            $targetPath = $this->backupDirectory() . DIRECTORY_SEPARATOR . $safeName;

            if ($safeName === '' || !is_file($targetPath) || (int) @filesize($targetPath) <= 0) {
                ResponseHelper::notFound(
                    'El archivo físico del respaldo no existe o está vacío en el servidor.'
                );
                return;
            }

            if (!$this->restorePhysicalDump($targetPath)) {
                ResponseHelper::internalError(
                    'No se pudo restaurar el respaldo mediante psql; verifique la integridad del archivo SQL.'
                );
                return;
            }

            AuditHelper::log(
                action: 'restauracion',
                entity: 'respaldo',
                recordId: $idRespaldo,
                newValue: [
                    'id_respaldo' => $idRespaldo,
                    'archivo'     => $safeName,
                ],
                reason: $motivo,
                userId: $adminUserId
            );

            ResponseHelper::success([
                'respaldo'   => $backup,
                'restaurado' => true,
            ], 'Respaldo restaurado exitosamente.');
        } catch (Throwable) {
            ResponseHelper::internalError('No se pudo completar la restauración del respaldo.');
        }
    }

    /**
     * Ejecuta el respaldo automático programado (CLI / cron) cuando hayan pasado
     * al menos 48 horas desde el último respaldo, o inmediatamente si $force = true.
     *
     * @return array{respaldo: array<string, mixed>, rotados: array<int, string>}|null
     */
    public function runScheduledAutoBackup(bool $force = false): ?array {
        if (!$force && !$this->backupModel->isAutoBackupDue()) {
            return null;
        }

        $fileName = sprintf('canariapp_auto_backup_%s_%s.sql', date('Ymd_His'), bin2hex(random_bytes(3)));

        if (!$this->createPhysicalDump($fileName)) {
            throw new RuntimeException('No se pudo generar el volcado automático con pg_dump.');
        }

        $result = $this->backupModel->registerAndRotate($fileName, null);
        if (is_string($result)) {
            $this->removePhysicalBackupIfExists($fileName);
            throw new RuntimeException('Error de dominio al registrar respaldo automático: ' . $result);
        }

        $createdId = $result['id_respaldo'];
        $rotatedFiles = $result['rotated_files'];

        foreach ($rotatedFiles as $expiredFile) {
            $this->removePhysicalBackupIfExists($expiredFile);
        }

        $created = $this->backupModel->findDetailed($createdId) ?? [
            'id_respaldo' => $createdId,
            'archivo'     => $fileName,
            'id_usuario'  => null,
        ];

        AuditHelper::log(
            action: 'insert',
            entity: 'respaldo',
            recordId: $createdId,
            newValue: [
                'archivo'    => $fileName,
                'automatico' => true,
                'rotados'    => $rotatedFiles,
            ],
            reason: 'Respaldo automático programado (cada 2 días)',
            userId: null
        );

        return [
            'respaldo' => $created,
            'rotados'  => $rotatedFiles,
        ];
    }

    /**
     * Verifica de forma silenciosa si corresponde ejecutar el respaldo automático cada 2 días.
     *
     * @return array{respaldo: array<string, mixed>, rotados: array<int, string>}|null
     */
    private function runAutomaticBackupIfDue(): ?array {
        try {
            return $this->runScheduledAutoBackup(false);
        } catch (Throwable $exception) {
            error_log('Auto-backup omitido por error: ' . $exception->getMessage());

            return null;
        }
    }

    /**
     * @param array<string, mixed> $input
     * @return array<string, string>
     */
    private function validateCreate(array $input): array {
        $errors = [];

        foreach (self::SERVER_FIELDS as $field) {
            if (array_key_exists($field, $input)) {
                $errors[$field] = 'Este campo lo asigna el servidor.';
            }
        }

        if (array_key_exists('archivo', $input) && $input['archivo'] !== null) {
            if (!is_string($input['archivo']) || trim($input['archivo']) === '') {
                $errors['archivo'] = 'El nombre de archivo no puede estar vacío.';
            } else {
                $clean = trim($input['archivo']);
                if (mb_strlen($clean) > 255) {
                    $errors['archivo'] = 'El nombre de archivo no puede superar los 255 caracteres.';
                } elseif (preg_match('/^[A-Za-z0-9._-]+$/', $clean) !== 1 || str_contains($clean, '..')) {
                    $errors['archivo'] = 'El nombre de archivo solo puede contener letras, números, puntos, guiones y guiones bajos.';
                }
            }
        }

        if (array_key_exists('motivo', $input) && $input['motivo'] !== null && !is_string($input['motivo'])) {
            $errors['motivo'] = 'El motivo debe ser una cadena de texto.';
        }

        return $errors;
    }

    /**
     * Genera el volcado SQL mediante pg_dump en storage/backups/ con --clean --if-exists
     * para garantizar su restaurabilidad (SRS-RF029).
     */
    private function createPhysicalDump(string $fileName): bool {
        if (!function_exists('exec')) {
            return false;
        }

        $backupDir = $this->backupDirectory();
        if (!is_dir($backupDir) && !@mkdir($backupDir, 0750, true) && !is_dir($backupDir)) {
            return false;
        }

        $db = $this->databaseCredentials();
        if ($db === null) {
            return false;
        }

        $targetPath = $backupDir . DIRECTORY_SEPARATOR . basename($fileName);
        if (is_file($targetPath)) {
            return false;
        }

        $command = sprintf(
            'PGPASSWORD=%s pg_dump -h %s -p %s -U %s -F p --clean --if-exists --no-owner --no-privileges -f %s %s 2>/dev/null',
            escapeshellarg($db['pass']),
            escapeshellarg($db['host']),
            escapeshellarg($db['port']),
            escapeshellarg($db['user']),
            escapeshellarg($targetPath),
            escapeshellarg($db['name'])
        );

        $output = [];
        $exitCode = 1;
        @exec($command, $output, $exitCode);

        if ($exitCode !== 0 || !is_file($targetPath) || (int) @filesize($targetPath) <= 0) {
            if (is_file($targetPath)) {
                @unlink($targetPath);
            }

            return false;
        }

        return true;
    }

    /**
     * Restaura un archivo SQL de respaldo en PostgreSQL mediante psql (SRS-RF029).
     */
    private function restorePhysicalDump(string $targetPath): bool {
        if (!function_exists('exec') || !is_file($targetPath)) {
            return false;
        }

        $db = $this->databaseCredentials();
        if ($db === null) {
            return false;
        }

        $sqlPreview = (string) @file_get_contents($targetPath, false, null, 0, 8192);
        if (stripos($sqlPreview, 'DROP TABLE') === false) {
            $resetCmd = sprintf(
                'PGPASSWORD=%s psql -v ON_ERROR_STOP=1 -h %s -p %s -U %s -d %s -c %s 2>/dev/null',
                escapeshellarg($db['pass']),
                escapeshellarg($db['host']),
                escapeshellarg($db['port']),
                escapeshellarg($db['user']),
                escapeshellarg($db['name']),
                escapeshellarg('DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public;')
            );
            $resetOut = [];
            $resetCode = 1;
            @exec($resetCmd, $resetOut, $resetCode);
            if ($resetCode !== 0) {
                return false;
            }
        }

        $command = sprintf(
            'PGPASSWORD=%s psql -v ON_ERROR_STOP=1 -h %s -p %s -U %s -d %s -f %s 2>/dev/null',
            escapeshellarg($db['pass']),
            escapeshellarg($db['host']),
            escapeshellarg($db['port']),
            escapeshellarg($db['user']),
            escapeshellarg($db['name']),
            escapeshellarg($targetPath)
        );

        $output = [];
        $exitCode = 1;
        @exec($command, $output, $exitCode);

        return $exitCode === 0;
    }

    /**
     * @return array{host: string, port: string, name: string, user: string, pass: string}|null
     */
    private function databaseCredentials(): ?array {
        $dbHost = (string) ($_ENV['DB_HOST'] ?? getenv('DB_HOST') ?: '');
        $dbPort = (string) ($_ENV['DB_PORT'] ?? getenv('DB_PORT') ?: '5432');
        $dbName = (string) ($_ENV['DB_NAME'] ?? $_ENV['DB_DATABASE'] ?? getenv('DB_NAME') ?: '');
        $dbUser = (string) ($_ENV['DB_USER'] ?? $_ENV['DB_USERNAME'] ?? getenv('DB_USER') ?: '');
        $dbPass = (string) ($_ENV['DB_PASS'] ?? $_ENV['DB_PASSWORD'] ?? getenv('DB_PASS') ?: '');

        if ($dbHost === '' || $dbName === '' || $dbUser === '') {
            return null;
        }

        return [
            'host' => $dbHost,
            'port' => $dbPort,
            'name' => $dbName,
            'user' => $dbUser,
            'pass' => $dbPass,
        ];
    }

    /**
     * Elimina del disco un respaldo antiguo retirado por la rotación de 7 archivos.
     */
    private function removePhysicalBackupIfExists(string $fileName): void {
        $safeName = basename(trim($fileName));
        if ($safeName === '' || $safeName === '.' || $safeName === '..') {
            return;
        }

        $targetPath = $this->backupDirectory() . DIRECTORY_SEPARATOR . $safeName;
        if (is_file($targetPath)) {
            @unlink($targetPath);
        }
    }

    private function backupDirectory(): string {
        return dirname(__DIR__, 2) . DIRECTORY_SEPARATOR . 'storage' . DIRECTORY_SEPARATOR . 'backups';
    }

    private function ensureAdminRole(): int {
        if (AuthMiddleware::userRole() !== 'administrador') {
            ResponseHelper::forbidden('Solo un administrador puede gestionar los respaldos del sistema.');
        }

        $userId = AuthMiddleware::userId();
        if ($userId === null || !is_numeric($userId)) {
            ResponseHelper::unauthorized('No hay un usuario autenticado.');
        }

        return (int) $userId;
    }

    /**
     * @return array<string, mixed>
     */
    private function readOptionalJsonBody(): array {
        $raw = file_get_contents('php://input');
        if ($raw === false || trim($raw) === '') {
            return [];
        }

        $decoded = json_decode($raw, true);
        if (!is_array($decoded)) {
            ResponseHelper::badRequest('El cuerpo de la petición debe ser un JSON válido.');
        }

        return $decoded;
    }

    private function respondDomainError(string $code): void {
        match ($code) {
            Backup::ERROR_DUPLICATE_FILE => ResponseHelper::conflict(
                'Ya existe un respaldo registrado con ese nombre de archivo.'
            ),
            Backup::ERROR_FORBIDDEN_ROLE => ResponseHelper::forbidden(
                'Solo un usuario con rol administrador puede registrar respaldos.'
            ),
            default => ResponseHelper::validationError([
                'respaldo' => 'Los datos del respaldo no cumplen las reglas de validación.',
            ]),
        };
    }
}